#!/usr/bin/env bash
# Oliver banner v2 — OB gradient uses the f.note green palette (stacked layers).

print_banner() {
  local oliver=(
    ' ██████╗ ██╗     ██╗██╗   ██╗███████╗██████╗ '
    '██╔═══██╗██║     ██║██║   ██║██╔════╝██╔══██╗'
    '██║   ██║██║     ██║╚██╗ ██╔╝█████╗  ██████╔╝'
    '██║   ██║██║     ██║ ╚████╔╝ ██╔══╝  ██╔══██╗'
    '╚██████╔╝███████╗██║  ╚██╔╝  ███████╗██║  ██║'
    ' ╚═════╝ ╚══════╝╚═╝   ╚═╝   ╚══════╝╚═╝  ╚═╝'
  )
  local big=(
    '  ████████████╗╗  ████████████╗╗'
    '  ████████████╗╗  ████████████╗╗'
    '████╔╔══════████╗╗████╔╔════████╗╗'
    '████╔╔══════████╗╗████╔╔════████╗╗'
    '████║║      ████║║████████████╔╔╝╝'
    '████║║      ████║║████████████╔╔╝╝'
    '████║║      ████║║████╔╔════████╗╗'
    '████║║      ████║║████╔╔════████╗╗'
    '╚╚████████████╔╔╝╝████████████╔╔╝╝'
    '╚╚████████████╔╔╝╝████████████╔╔╝╝'
    '  ╚╚══════════╝╝  ╚╚══════════╝╝  '
    '  ╚╚══════════╝╝  ╚╚══════════╝╝  '
  )
  local subtitle='Build One Ideas'
  local -a grad=(
    '62;107;92'
    '62;107;92'
    '62;107;92'
    '94;143;124'
    '94;143;124'
    '94;143;124'
    '236;238;234'
    '87;183;142'
    '87;183;142'
    '87;183;142'
    '87;183;142'
    '87;183;142'
  )
  local right_width=45 gap=6
  local row plain right
  for ((row = 0; row < ${#big[@]}; row++)); do
    plain=''
    right=''
    if ((row >= 2 && row <= 7)); then
      plain="${oliver[row - 2]}"
      right="$(printf '\033[1;38;5;189m%s\033[0m' "$plain")"
    elif ((row == 9)); then
      plain="$(printf '%*s%s' "$((right_width - ${#subtitle}))" '' "$subtitle")"
      right="$(printf '\033[38;5;189m%s\033[0m' "$plain")"
    fi
    printf '\033[38;2;%sm%s\033[0m' "${grad[row]}" "${big[row]}"
    printf '%*s' "$gap" ''
    printf '%s\n' "$right"
  done
}

# --- demo ---
print_banner
echo
echo "  Oliver's script — description line goes here"
