#!/usr/bin/env bash
# Oliver banner v4 — big "B1" with a hand-drawn ASCII lightbulb, f.note palette.

print_banner() {
  local oliver=(
    ' ██████╗ ██╗     ██╗██╗   ██╗███████╗██████╗ '
    '██╔═══██╗██║     ██║██║   ██║██╔════╝██╔══██╗'
    '██║   ██║██║     ██║╚██╗ ██╔╝█████╗  ██████╔╝'
    '██║   ██║██║     ██║ ╚████╔╝ ██╔══╝  ██╔══██╗'
    '╚██████╔╝███████╗██║  ╚██╔╝  ███████╗██║  ██║'
    ' ╚═════╝ ╚══════╝╚═╝   ╚═╝   ╚══════╝╚═╝  ╚═╝'
  )
  local b1=(
    '████████████╗╗    ████╗╗'
    '████████████╗╗    ████╗╗'
    '████╔╔════████╗╗██████║║'
    '████╔╔════████╗╗██████║║'
    '████████████╔╔╝╝╚╚████║║'
    '████████████╔╔╝╝╚╚████║║'
    '████╔╔════████╗╗  ████║║'
    '████╔╔════████╗╗  ████║║'
    '████████████╔╔╝╝  ████║║'
    '████████████╔╔╝╝  ████║║'
    '╚╚══════════╝╝    ╚╚══╝╝'
    '╚╚══════════╝╝    ╚╚══╝╝'
  )
  local bulb=(
    '     ██████'
    '   ██████████'
    '  ████████████'
    '  ████████████'
    '  ████████████'
    '  ████████████'
    '   ██████████'
    '    ████████'
    '      ████'
    '     ██████'
    '     ██████'
    '      ████'
  )
  local subtitle='Build One Ideas'
  local -a grad=(
    '62;107;92'
    '62;107;92'
    '62;107;92'
    '94;143;124'
    '94;143;124'
    '94;143;124'
    '236;238;234'
    '87;183;142'
    '87;183;142'
    '87;183;142'
    '87;183;142'
    '87;183;142'
  )
  local -a bulb_col=(
    '247;209;84'
    '247;209;84'
    '247;209;84'
    '247;209;84'
    '247;209;84'
    '247;209;84'
    '247;209;84'
    '247;209;84'
    '247;209;84'
    '156;163;175'
    '156;163;175'
    '107;114;128'
  )
  local left_width=40 gap=2 right_width=45
  local row right
  for ((row = 0; row < 12; row++)); do
    right=''
    if ((row >= 2 && row <= 7)); then
      right="$(printf '\033[1;38;5;189m%s\033[0m' "${oliver[row - 2]}")"
    elif ((row == 9)); then
      right="$(printf '\033[38;5;189m%*s%s\033[0m' "$((right_width - ${#subtitle}))" '' "$subtitle")"
    fi
    printf '\033[38;2;%sm%s\033[0m  ' "${grad[row]}" "${b1[row]}"
    printf '\033[38;2;%sm%s\033[0m' "${bulb_col[row]}" "${bulb[row]}"
    printf '%*s' "$((left_width + gap - ${#bulb[row]}))" ''
    printf '%s\n' "$right"
  done
}

# --- demo ---
print_banner
echo
echo "  Oliver's script — description line goes here"
